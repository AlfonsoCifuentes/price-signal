#!/usr/bin/env python3
"""Build the public Pricing Demo workbook from the public CSVs only.

Every headline metric is a live Excel formula over the data sheets. Run
`python recalc_and_verify_workbook.py` afterwards (Windows + Excel) to let Excel
calculate, store cached values and check them against public_analysis.json.
"""
from pathlib import Path
import csv, json
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.chart import BarChart, Reference
from openpyxl.worksheet.table import Table, TableStyleInfo
from openpyxl.formatting.rule import FormulaRule
from openpyxl.utils import get_column_letter as L

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / '02_PUBLIC_CASE_STUDY'
OUT = HERE / 'Pricing_Demo_Analysis_Workbook.xlsx'
A = json.loads((SRC / 'public_analysis.json').read_text(encoding='utf-8'))

INK, PAPER, RED, MUTED, PALE = '1B1C19', 'EFEDE6', 'D2452A', '6B6B63', 'F7F5EF'
F_HEAD = Font(name='Arial', bold=True, color=PAPER, size=10)
F_BODY = Font(name='Arial', size=10, color=INK)
F_MONO = Font(name='Consolas', size=10, color=INK)
F_TITLE = Font(name='Arial', bold=True, size=22, color=INK)
F_KICK = Font(name='Consolas', size=9, color=RED, bold=True)
F_NOTE = Font(name='Arial', italic=True, size=9, color=MUTED)
FILL_HEAD = PatternFill('solid', fgColor=INK)
FILL_PAPER = PatternFill('solid', fgColor=PAPER)
FILL_PALE = PatternFill('solid', fgColor=PALE)
FILL_RED = PatternFill('solid', fgColor='F6D8CF')
THIN = Border(bottom=Side(style='thin', color='CFCBBF'))
EUR = '€#,##0.00'
WRAP = Alignment(wrap_text=True, vertical='top')


def read(name):
    with (SRC / name).open(encoding='utf-8-sig', newline='') as f:
        return list(csv.DictReader(f))


raw, enh = read('public_raw_catalogue.csv'), read('public_enriched_catalogue.csv')
N = len(enh)
LAST = N + 1
wb = Workbook()


def header(ws, row, labels, widths=None):
    for i, lab in enumerate(labels, start=1):
        c = ws.cell(row=row, column=i, value=lab)
        c.font, c.fill = F_HEAD, FILL_HEAD
        c.alignment = Alignment(vertical='center', wrap_text=True)
    ws.row_dimensions[row].height = 30
    if widths:
        for i, w in enumerate(widths, start=1):
            ws.column_dimensions[L(i)].width = w


def kicker(ws, text, title, note=None):
    ws['A1'] = text
    ws['A1'].font = F_KICK
    ws['A2'] = title
    ws['A2'].font = F_TITLE
    ws.row_dimensions[2].height = 34
    if note:
        ws['A3'] = note
        ws['A3'].font = F_NOTE
    ws.sheet_view.showGridLines = False


def body(ws, r1, r2, c1, c2, money_cols=(), mono_cols=()):
    for r in range(r1, r2 + 1):
        for c in range(c1, c2 + 1):
            cell = ws.cell(row=r, column=c)
            cell.font = F_MONO if c in mono_cols else F_BODY
            cell.border = THIN
            if c in money_cols:
                cell.number_format = EUR


def add_table(ws, ref, name):
    t = Table(displayName=name, ref=ref)
    t.tableStyleInfo = TableStyleInfo(name='TableStyleLight1', showRowStripes=True)
    ws.add_table(t)


# ------------------------------------------------------------------ README
ws = wb.active
ws.title = 'README'
kicker(ws, 'PRICING DEMO — BY ALFONSO CIFUENTES · INDEPENDENT SYNTHETIC CASE STUDY', 'Before you compare prices, compare products.')
lines = [
    ('Origin', 'Pricing Demo by Alfonso Cifuentes grew out of a technical assessment completed during a recruitment process for a data analyst role at an international educational publisher. It is an independent reconstruction: no employer catalogue, product or price is included.'),
    ('What this is', 'A fully fictional educational-publishing catalogue (362 products, 12 invented series) built to practise like-for-like price analysis and data-quality review.'),
    ('What it is not', 'Not real publisher data. No sales, units, costs, margins, discounts or demand. EUR values are invented list prices, never transactions.'),
    ('Provenance', 'Generated by 02_PUBLIC_CASE_STUDY/generate_independent_dataset.py (seed 20261011) and analysed by analyze_catalogue.py. Same inputs always give byte-identical files.'),
    ('How the numbers work', 'Every figure on Summary, Groups, Split_Volumes and Answer_Keys is a live formula over Raw_Catalogue / Enriched. Change a price and the results follow.'),
    ('Comparable group', 'Rows that share series, product type, role, book part, pack, answer support, digital access, extra resources and edition. A group is comparable when it spans 2+ levels; stable when all its prices are equal.'),
    ('Series repair', 'Enriched!Title_Series derives the series from the title prefix. The source Series field is kept untouched; Groups_Repaired recounts with the derived value as a reporting view.'),
    ('Sheets', 'Summary · Groups · Groups_Repaired · Exceptions · Split_Volumes · Answer_Keys · Quality_Register · Type_Stats · Enriched · Raw_Catalogue'),
    ('Licence', 'Synthetic data and text: CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/). Credit Alfonso Cifuentes and keep the fictional-data disclosure.'),
]
for i, (k, v) in enumerate(lines, start=5):
    ws.cell(row=i, column=1, value=k).font = Font(name='Arial', bold=True, size=10, color=INK)
    c = ws.cell(row=i, column=2, value=v)
    c.font, c.alignment = F_BODY, WRAP
    ws.row_dimensions[i].height = 44
ws.column_dimensions['A'].width = 24
ws.column_dimensions['B'].width = 110

# ------------------------------------------------------------------ Raw_Catalogue
ws = wb.create_sheet('Raw_Catalogue')
cols = ['Series', 'Segment', 'Sub-Segment', 'Title', 'Price_EUR']
header(ws, 1, cols, [22, 12, 17, 58, 12])
for r in raw:
    ws.append([r[k] if k != 'Price_EUR' else float(r[k]) for k in cols])
body(ws, 2, LAST, 1, 5, money_cols=(5,))
add_table(ws, f'A1:E{LAST}', 'tRaw')
ws.freeze_panes = 'A2'

# ------------------------------------------------------------------ Enriched (+ formula helper columns)
ws = wb.create_sheet('Enriched')
ecols = list(enh[0].keys())  # 19 columns, Price_EUR last (S)
helper = ['Row_ID', 'Title_Series', 'Series_Check', 'Group_Key', 'Group_Key_Repaired', 'Group_Min', 'Group_Max']
header(ws, 1, ecols + helper, [20, 10, 15, 52, 15, 9, 10, 16, 15, 9, 12, 13, 11, 11, 9, 9, 26, 12, 11, 8, 20, 14, 46, 46, 11, 11])
series_list = sorted({r['Series'] for r in enh})
for i, r in enumerate(enh, start=2):
    vals = [r[k] if k != 'Price_EUR' else float(r[k]) for k in ecols]
    ws.append(vals)
    ws.cell(row=i, column=20, value=i - 1)
    # Series implied by the title prefix (lookup against the list of series on Type_Stats!K)
    ws.cell(row=i, column=21, value=f'=LOOKUP(2,1/(LEFT(D{i},LEN(SeriesList)+1)=SeriesList&" "),SeriesList)')
    ws.cell(row=i, column=22, value=f'=IF(U{i}=A{i},"OK","MISMATCH")')
    key = '&"|"&'.join(f'{c}{i}' for c in 'HIJKLMNQE')  # type role part pack key main-digital practice-digital resources edition
    ws.cell(row=i, column=23, value=f'=A{i}&"|"&{key}')
    ws.cell(row=i, column=24, value=f'=U{i}&"|"&{key}')
    ws.cell(row=i, column=25, value=f'=MINIFS($S$2:$S${LAST},$W$2:$W${LAST},W{i})')
    ws.cell(row=i, column=26, value=f'=MAXIFS($S$2:$S${LAST},$W$2:$W${LAST},W{i})')
body(ws, 2, LAST, 1, 26, money_cols=(19, 25, 26), mono_cols=(23, 24))
add_table(ws, f'A1:Z{LAST}', 'tEnriched')
ws.freeze_panes = 'E2'
ws.conditional_formatting.add(f'V2:V{LAST}', FormulaRule(formula=[f'V2="MISMATCH"'], fill=FILL_RED, font=Font(bold=True, color=RED)))
ws.conditional_formatting.add(f'S2:S{LAST}', FormulaRule(formula=[f'$Y2<>$Z2'], fill=FILL_RED))

# ------------------------------------------------------------------ Groups (as-recorded and repaired)
GROUP = ['Series', 'Product_Type', 'Product_Role', 'Book_Part', 'Pack_Type', 'Answer_Support',
         'Digital_Main_Book_Access', 'Digital_Practice_Book_Access', 'Additional_Resources', 'Edition']
TITLES = {r['Title']: r['Series'] for r in enh}


def prefix(title):
    return next(s for s in sorted(series_list, key=len, reverse=True) if title.startswith(s + ' '))


def make_groups(name, keycol, repaired):
    ws = wb.create_sheet(name)
    kicker(ws, 'CROSS-LEVEL COMPARABILITY' + (' — SERIES REPAIRED FROM TITLE PREFIX' if repaired else ' — AS RECORDED'),
           'Groups' + (' after repairing two misfiled records' if repaired else ' of identical configurations'),
           'Each row is one configuration. Levels is a distinct count; Comparable = 2+ levels; Stable = one price across all its levels.')
    header(ws, 5, ['Group_Key', 'Records', 'Levels', 'Min_EUR', 'Max_EUR', 'Spread_EUR', 'Comparable', 'Stable'],
           [92, 9, 8, 11, 11, 11, 12, 9])
    keys = []
    for r in enh:
        s = prefix(r['Title']) if repaired else r['Series']
        k = '|'.join([s] + [r[c] for c in GROUP[1:3]] + [r['Book_Part'], r['Pack_Type'], r['Answer_Support'],
                     r['Digital_Main_Book_Access'], r['Digital_Practice_Book_Access'], r['Additional_Resources'], r['Edition']])
        if k not in keys:
            keys.append(k)
    rng = f'Enriched!${keycol}$2:${keycol}${LAST}'
    lv = f'Enriched!$F$2:$F${LAST}'
    pr = f'Enriched!$S$2:$S${LAST}'
    for i, k in enumerate(keys, start=6):
        ws.cell(row=i, column=1, value=k)
        ws.cell(row=i, column=2, value=f'=COUNTIF({rng},A{i})')
        ws.cell(row=i, column=3, value=f'=SUMPRODUCT(({rng}=A{i})/COUNTIFS({rng},{rng},{lv},{lv}))')
        ws.cell(row=i, column=4, value=f'=MINIFS({pr},{rng},A{i})')
        ws.cell(row=i, column=5, value=f'=MAXIFS({pr},{rng},A{i})')
        ws.cell(row=i, column=6, value=f'=E{i}-D{i}')
        ws.cell(row=i, column=7, value=f'=IF(ROUND(C{i},6)>1,"YES","no")')
        ws.cell(row=i, column=8, value=f'=IF(G{i}="YES",IF(D{i}=E{i},"YES","NO"),"—")')
    end = 5 + len(keys)
    body(ws, 6, end, 1, 8, money_cols=(4, 5, 6), mono_cols=(1,))
    ws.conditional_formatting.add(f'A6:H{end}', FormulaRule(formula=['$H6="NO"'], fill=FILL_RED, font=Font(bold=True, color=RED)))
    ws.freeze_panes = 'B6'
    return end


g_end = make_groups('Groups', 'W', False)
gr_end = make_groups('Groups_Repaired', 'X', True)

# ------------------------------------------------------------------ Exceptions
ws = wb.create_sheet('Exceptions')
kicker(ws, 'THE SIX EXCEPTIONS', 'Four look like pricing. Two are data errors.',
       'Classification from analyze_catalogue.py. Prices are looked up live from Enriched by title.')
